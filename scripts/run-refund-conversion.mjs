import { createClient } from '@supabase/supabase-js';

const url = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!url || !serviceRoleKey) {
  console.error('Missing SUPABASE_URL/VITE_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY');
  process.exit(1);
}

const supabase = createClient(url, serviceRoleKey, { auth: { persistSession: false } });

async function ensurePlatformSettings() {
  const { data: existing, error } = await supabase
    .from('platform_settings')
    .select('*')
    .limit(1)
    .maybeSingle();

  if (error) throw error;
  if (existing) return existing;

  const { data, error: insertError } = await supabase
    .from('platform_settings')
    .insert({
      pool_to_points_exchange_rate: 1.0,
      pool_points_expiry_days: 30,
      school_refund_batch_interval_days: 15,
      default_pos_accepts_cash: false,
    })
    .select()
    .single();

  if (insertError) throw insertError;
  return data;
}

async function getContributorContext(profileId, fallbackSchoolId) {
  const [{ data: profile }, { data: student }] = await Promise.all([
    supabase.from('profiles').select('school_id').eq('id', profileId).maybeSingle(),
    supabase.from('students').select('id').eq('user_id', profileId).maybeSingle(),
  ]);

  return {
    schoolId: profile?.school_id || fallbackSchoolId,
    contributorStudentId: student?.id || null,
  };
}

async function ensureEligibleConversions(expiryDays) {
  const threshold = new Date();
  threshold.setUTCDate(threshold.getUTCDate() - expiryDays);
  const thresholdDate = threshold.toISOString().slice(0, 10);
  let created = 0;

  const { data: pools, error: poolsError } = await supabase
    .from('birthday_pools')
    .select('id, birthday_student_id, birthday_date, status, collected_amount')
    .lte('birthday_date', thresholdDate)
    .gt('collected_amount', 0);

  if (poolsError) throw poolsError;

  for (const pool of (pools || []).filter((item) => !['DELIVERED', 'REFUNDED'].includes(item.status))) {
    const { data: birthdayStudent, error: studentError } = await supabase
      .from('students')
      .select('school_id')
      .eq('id', pool.birthday_student_id)
      .maybeSingle();

    if (studentError || !birthdayStudent?.school_id) {
      console.warn(`Skipping pool ${pool.id}: missing birthday student school`);
      continue;
    }

    const [{ data: existing }, { data: contributions, error: contributionsError }] = await Promise.all([
      supabase.from('pool_point_conversions').select('contributor_profile_id').eq('pool_id', pool.id),
      supabase.from('pool_contributions').select('contributor_id, amount').eq('pool_id', pool.id),
    ]);

    if (contributionsError) throw contributionsError;

    const existingProfiles = new Set((existing || []).map((item) => item.contributor_profile_id));
    const eligibleAt = new Date(`${pool.birthday_date}T12:00:00.000Z`);
    eligibleAt.setUTCDate(eligibleAt.getUTCDate() + expiryDays);

    for (const contribution of contributions || []) {
      if (existingProfiles.has(contribution.contributor_id)) continue;

      const contributorContext = await getContributorContext(contribution.contributor_id, birthdayStudent.school_id);

      const { error: insertError } = await supabase.from('pool_point_conversions').insert({
        pool_id: pool.id,
        contributor_profile_id: contribution.contributor_id,
        contributor_student_id: contributorContext.contributorStudentId,
        school_id: contributorContext.schoolId,
        original_contribution_amount: contribution.amount,
        conversion_rate: 1.0,
        multiplier_applied: 1.0,
        status: 'pending',
        eligible_at: eligibleAt.toISOString(),
        notes: 'Generated by scheduled conversion runner',
      });

      if (insertError) throw insertError;
      created += 1;
    }
  }

  return created;
}

async function main() {
  const settings = await ensurePlatformSettings();
  const queued = await ensureEligibleConversions(settings.pool_points_expiry_days || 30);

  const nowIso = new Date().toISOString();
  const { data: conversions, error: conversionError } = await supabase
    .from('pool_point_conversions')
    .select('*')
    .eq('status', 'pending')
    .lte('eligible_at', nowIso);

  if (conversionError) throw conversionError;

  let converted = 0;
  const errors = [];

  for (const conversion of conversions || []) {
    try {
      const { data: schoolSettings } = await supabase
        .from('school_settings')
        .select('pool_points_multiplier')
        .eq('school_id', conversion.school_id)
        .maybeSingle();

      const multiplier = schoolSettings?.pool_points_multiplier || 1.0;
      const exchangeRate = settings.pool_to_points_exchange_rate || 1.0;
      const points = Math.round(conversion.original_contribution_amount * exchangeRate * multiplier);

      const { data: lastEntry } = await supabase
        .from('points_ledger')
        .select('balance_after')
        .eq('profile_id', conversion.contributor_profile_id)
        .eq('school_id', conversion.school_id)
        .order('created_at', { ascending: false })
        .limit(1)
        .maybeSingle();

      const balanceAfter = (lastEntry?.balance_after || 0) + points;

      const { error: insertError } = await supabase.from('points_ledger').insert({
        profile_id: conversion.contributor_profile_id,
        student_id: conversion.contributor_student_id,
        school_id: conversion.school_id,
        transaction_type: 'POOL_CONVERSION',
        amount: points,
        source_module: 'pool',
        source_id: conversion.pool_id,
        source_description: 'Expired birthday pool contribution converted to points',
        balance_after: balanceAfter,
        notes: `Pool conversion ID: ${conversion.id}`,
      });

      if (insertError) throw insertError;

      const { error: updateError } = await supabase.from('pool_point_conversions').update({
        status: 'converted',
        converted_at: nowIso,
        points_awarded: points,
        multiplier_applied: multiplier,
        conversion_rate: exchangeRate,
        updated_at: nowIso,
        error_message: null,
      }).eq('id', conversion.id);

      if (updateError) throw updateError;
      converted += 1;
    } catch (error) {
      errors.push(`${conversion.id}: ${error.message || String(error)}`);
      await supabase.from('pool_point_conversions').update({
        status: 'failed',
        error_message: error.message || String(error),
        updated_at: nowIso,
      }).eq('id', conversion.id);
    }
  }

  console.log(JSON.stringify({ queued, converted, errors, timestamp: nowIso }, null, 2));

  if (errors.length > 0) {
    process.exitCode = 1;
  }
}

main().catch((error) => {
  console.error('Scheduled refund conversion failed');
  console.error(error);
  process.exit(1);
});